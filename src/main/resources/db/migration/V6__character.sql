create table character
(
    id          bigint generated by default as identity primary key,
    name        varchar(128)             not null,
    aliases     text,
    series      varchar(128),
    description text,
    created_at  timestamp with time zone not null default current_timestamp,
    updated_at  timestamp with time zone not null default current_timestamp
);

create unique index uk_character_name on character (name);

create table character_reference
(
    id           bigint generated by default as identity primary key,
    character_id bigint                   not null references character (id),
    asset_id     bigint,
    embedding    text                     not null,
    source       varchar(16)              not null default 'MANUAL',
    weight       double precision         not null default 1,
    created_at   timestamp with time zone not null default current_timestamp
);

create index idx_character_reference_character on character_reference (character_id);
create index idx_character_reference_asset on character_reference (asset_id);

alter table asset add column character_id bigint;
alter table asset add column character_confidence double precision;

create index idx_asset_character on asset (character_id);
