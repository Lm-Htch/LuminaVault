create table asset_embedding
(
    asset_id    bigint primary key references asset (id),
    description text,
    tags        text,
    embedding   text,
    model       varchar(128),
    status      varchar(16)              not null default 'PENDING',
    error       varchar(512),
    updated_at  timestamp with time zone not null default current_timestamp
);

create index idx_asset_embedding_status on asset_embedding (status);

create table asset_feedback
(
    id         bigint generated by default as identity primary key,
    user_id    bigint                   not null,
    asset_id   bigint                   not null,
    query_text text,
    action     varchar(16)              not null,
    weight     double precision         not null default 1,
    embedding  text,
    created_at timestamp with time zone not null default current_timestamp
);

create index idx_asset_feedback_user on asset_feedback (user_id);
create index idx_asset_feedback_asset on asset_feedback (asset_id);
